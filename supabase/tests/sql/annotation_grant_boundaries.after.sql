DO $$
DECLARE attorney uuid; owner uuid; outsider uuid; new_grant uuid; case_id uuid; file_a uuid; entry_a uuid; n integer; row_id uuid;
BEGIN
 SELECT id INTO attorney FROM annotation_qa_ids WHERE label='attorney';
 SELECT id INTO owner FROM annotation_qa_ids WHERE label='owner';
 SELECT id INTO outsider FROM annotation_qa_ids WHERE label='outsider';
 SELECT id INTO new_grant FROM annotation_qa_ids WHERE label='new_grant';
 SELECT id INTO case_id FROM annotation_qa_ids WHERE label='case';
 SELECT id INTO file_a FROM annotation_qa_ids WHERE label='file_a';
 SELECT id INTO entry_a FROM annotation_qa_ids WHERE label='entry_a';
 IF NOT EXISTS(SELECT 1 FROM public.attorney_evidence_reviews WHERE id=(SELECT id FROM annotation_qa_ids WHERE label='old_review') AND link_id=(SELECT id FROM annotation_qa_ids WHERE label='old_grant')) THEN RAISE EXCEPTION 'Legacy review did not remain bound to its ended grant'; END IF;
 INSERT INTO public.attorney_evidence_reviews(id,link_id,attorney_user_id,client_user_id,evidence_id,notes) SELECT id,new_grant,attorney,owner,file_a,'Fictional current review' FROM annotation_qa_ids WHERE label='new_review';
 INSERT INTO public.attorney_evidence_reviews(id,link_id,attorney_user_id,client_user_id,evidence_id,linked_incident_id,notes) SELECT id,new_grant,attorney,owner,(SELECT id FROM annotation_qa_ids WHERE label='file_b'),(SELECT id FROM annotation_qa_ids WHERE label='entry_b'),'Fictional excluded entry reference' FROM annotation_qa_ids WHERE label='hidden_review';
 INSERT INTO public.attorney_incident_notes(id,link_id,attorney_user_id,client_user_id,incident_id,note) SELECT id,new_grant,attorney,owner,CASE WHEN label='current_note' THEN entry_a ELSE (SELECT id FROM annotation_qa_ids WHERE label='entry_b') END,'Fictional annotation' FROM annotation_qa_ids WHERE label IN('current_note','hidden_note');
 INSERT INTO public.attorney_missing_evidence_checklist(id,link_id,attorney_user_id,client_user_id,item_label) SELECT id,new_grant,attorney,owner,'Fictional current checklist' FROM annotation_qa_ids WHERE label='new_checklist';
 INSERT INTO public.court_dates(id,user_id,court_name,hearing_type,hearing_at) SELECT id,owner,'Fictional court','Fictional hearing',now()+interval '1 day' FROM annotation_qa_ids WHERE label='calendar';
 INSERT INTO public.attorney_messages(id,link_id,sender_user_id,sender_role,content) SELECT id,new_grant,owner,'survivor','Fictional message' FROM annotation_qa_ids WHERE label='message';
 INSERT INTO public.clio_matter_links(id,attorney_client_link_id,clio_matter_id,linked_by) SELECT id,new_grant,'fictional-matter',attorney FROM annotation_qa_ids WHERE label='clio';
 -- Own current records are positive controls; the same re-shared file does
 -- not reveal old reviews, and scope changes apply to direct API reads too.
 PERFORM set_config('request.jwt.claim.sub',attorney::text,true); PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',attorney,'role','authenticated')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 SELECT count(*) INTO n FROM public.attorney_evidence_reviews WHERE client_user_id=owner;
 IF n<>1 THEN RAISE EXCEPTION 'Current review missing or earlier/excluded review leaked'; END IF;
 SELECT count(*) INTO n FROM public.attorney_incident_notes WHERE client_user_id=owner;
 IF n<>1 THEN RAISE EXCEPTION 'Selected note missing or excluded entry note leaked'; END IF;
 SELECT count(*) INTO n FROM public.attorney_missing_evidence_checklist WHERE client_user_id=owner;
 IF n<>1 THEN RAISE EXCEPTION 'Current checklist missing or earlier grant checklist leaked'; END IF;
 SELECT count(*) INTO n FROM public.court_dates WHERE user_id=owner;
 IF n<>0 THEN RAISE EXCEPTION 'Unshared calendar leaked to linked attorney'; END IF;
 IF has_table_privilege('authenticated','public.attorney_messages','TRUNCATE') THEN RAISE EXCEPTION 'Browser retained destructive message privilege'; END IF;
 BEGIN UPDATE public.attorney_messages SET content='Forged' WHERE link_id=new_grant; RAISE EXCEPTION 'Browser changed a message body'; EXCEPTION WHEN insufficient_privilege THEN NULL; END;
 BEGIN UPDATE public.attorney_evidence_reviews SET notes='Forged' WHERE client_user_id=owner; RAISE EXCEPTION 'Browser bypassed annotation handler'; EXCEPTION WHEN insufficient_privilege THEN NULL; END;
 BEGIN UPDATE public.clio_matter_links SET clio_matter_id='wrong-destination' WHERE attorney_client_link_id=new_grant; RAISE EXCEPTION 'Browser changed Clio destination'; EXCEPTION WHEN insufficient_privilege THEN NULL; END;
 UPDATE public.clio_matter_links SET unlinked_at=now() WHERE attorney_client_link_id=new_grant;
 GET DIAGNOSTICS n=ROW_COUNT;
 IF n<>1 THEN RAISE EXCEPTION 'Legitimate Clio unlink is blocked'; END IF;
 EXECUTE 'RESET ROLE';
 PERFORM set_config('request.jwt.claim.sub','',true); PERFORM set_config('request.jwt.claims','{}',true);
 PERFORM set_config('request.jwt.claim.sub',outsider::text,true); EXECUTE 'SET LOCAL ROLE authenticated';
 IF private.current_annotation_grant(new_grant,attorney,owner) THEN RAISE EXCEPTION 'Helper accepted a spoofed actor'; END IF;
 SELECT count(*) INTO n FROM public.attorney_evidence_reviews WHERE client_user_id=owner;
 IF n<>0 THEN RAISE EXCEPTION 'Other account read reviews'; END IF;
 EXECUTE 'RESET ROLE';
 -- Approval changes apply even when the browser keeps its prior JWT.
 PERFORM set_config('request.jwt.claim.sub','',true);
 UPDATE public.attorney_access_applications SET status='rejected' WHERE user_id=attorney;
 PERFORM set_config('request.jwt.claim.sub',attorney::text,true); EXECUTE 'SET LOCAL ROLE authenticated';
 SELECT count(*) INTO n FROM public.attorney_evidence_reviews WHERE client_user_id=owner;
 IF n<>0 THEN RAISE EXCEPTION 'Revoked approval retained cached-token review access'; END IF;
 EXECUTE 'RESET ROLE'; PERFORM set_config('request.jwt.claim.sub','',true);
 UPDATE public.attorney_access_applications SET status='approved' WHERE user_id=attorney;
 DELETE FROM public.user_roles WHERE user_id=attorney AND role='attorney';
 PERFORM set_config('request.jwt.claim.sub',attorney::text,true); EXECUTE 'SET LOCAL ROLE authenticated';
 SELECT count(*) INTO n FROM public.attorney_evidence_reviews WHERE client_user_id=owner;
 IF n<>0 THEN RAISE EXCEPTION 'Removed role retained cached-token review access'; END IF;
 EXECUTE 'RESET ROLE'; PERFORM set_config('request.jwt.claim.sub','',true);
 INSERT INTO public.user_roles(user_id,role) VALUES(attorney,'attorney');
 UPDATE public.evidence SET deleted_at=now() WHERE id=file_a;
 PERFORM set_config('request.jwt.claim.sub',attorney::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 SELECT count(*) INTO n FROM public.attorney_evidence_reviews WHERE client_user_id=owner;
 IF n<>0 THEN RAISE EXCEPTION 'Deleted file review remained visible'; END IF;
 EXECUTE 'RESET ROLE'; PERFORM set_config('request.jwt.claim.sub','',true);
 UPDATE public.evidence SET deleted_at=NULL WHERE id=file_a;
 UPDATE public.cases SET attached_evidence_ids='{}'::uuid[],highlighted_incident_ids='{}'::uuid[] WHERE id=case_id;
 PERFORM set_config('request.jwt.claim.sub',attorney::text,true); EXECUTE 'SET LOCAL ROLE authenticated';
 SELECT count(*) INTO n FROM public.attorney_evidence_reviews WHERE client_user_id=owner;
 IF n<>0 THEN RAISE EXCEPTION 'Removed case attachment remained visible'; END IF;
 SELECT count(*) INTO n FROM public.attorney_incident_notes WHERE client_user_id=owner;
 IF n<>0 THEN RAISE EXCEPTION 'Removed case entry note remained visible'; END IF;
 EXECUTE 'RESET ROLE'; PERFORM set_config('request.jwt.claim.sub','',true);
 UPDATE public.attorney_client_links SET expires_at=now()-interval '1 second' WHERE id=new_grant;
 PERFORM set_config('request.jwt.claim.sub',attorney::text,true); EXECUTE 'SET LOCAL ROLE authenticated';
 SELECT count(*) INTO n FROM public.attorney_missing_evidence_checklist WHERE client_user_id=owner;
 IF n<>0 THEN RAISE EXCEPTION 'Expired grant checklist remained visible'; END IF;
 EXECUTE 'RESET ROLE';
 PERFORM set_config('request.jwt.claim.sub',owner::text,true); EXECUTE 'SET LOCAL ROLE authenticated';
 SELECT count(*) INTO n FROM public.court_dates WHERE user_id=owner;
 IF n<>1 THEN RAISE EXCEPTION 'Owner lost their calendar'; END IF;
 EXECUTE 'RESET ROLE'; PERFORM set_config('request.jwt.claim.sub','',true); PERFORM set_config('request.jwt.claims','{}',true);
 IF (SELECT count(*) FROM public.attorney_evidence_reviews WHERE client_user_id=owner)<>3 THEN RAISE EXCEPTION 'Historical reviews were destroyed'; END IF;
 RAISE NOTICE 'PASS: grant-bound annotation reads, repeated-file re-sharing, selection and case removal, expiry, caller binding, message integrity, calendar ownership and limited Clio updates';
END;
$$;
ROLLBACK;
SELECT 'annotation grant boundary checks passed; synthetic records rolled back' AS result;
